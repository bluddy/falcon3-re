#!/usr/bin/env python3
"""Generate src/asm/frameless_families.asm - annotated hand-ASM family notes.

Members come from classification.json (findings 13/14); disasm from capstone.
Hand-written family headers are embedded below; regenerable when classification
changes.
"""
import json

from capstone import Cs, CS_ARCH_X86, CS_MODE_16

CLS = "analysis/ida_falconcd/classification.json"
FB = "analysis/ida_falconcd/function_bytes.json"
OUT = "src/asm/frameless_families.asm"

FAMILY_HEADERS = {
    "FAR_THUNK": (
        "FAR-ENTRY THUNKS (classification: 'far stub: call next-near-func; retf')\n"
        ";-----------------------------------------------------------------------\n"
        "; Structure: E8 01 00  CB   = call near_next; retf\n"
        "; The call lands on the instruction IMMEDIATELY AFTER the retf - i.e. the\n"
        "; real (near) routine that follows in the segment.  Makes a near function\n"
        "; far-callable: caller far-calls the stub, stub near-calls the body, body\n"
        "; returns near, stub returns far.  Generated by RTLink for cross-segment\n"
        "; references to near functions.  CLASS: structural, NOT C - do not port.\n"
        "; Evidence: findings 14.  All 7 members share identical bytes.\n"
    ),
    "CS_GETTER": (
        "CS-RELATIVE NEAR-DATA ACCESSORS (classification: 'CS-relative data access')\n"
        ";-----------------------------------------------------------------------\n"
        "; Load/store tiny values held in the CODE segment (jump tables, flags,\n"
        "; selector bytes) through CS overrides, then retf.  Hand-written: MSC 5.1\n"
        "; large model would emit DS-relative accesses for C globals.\n"
        "; Sub-patterns:\n"
        ";   2E A1 xx xx CB  mov ax, cs:[xx]     ; word getter\n"
        ";   2E A0 xx xx CB  mov al, cs:[xx]     ; byte getter\n"
        ";   2E A2 xx xx CB  mov cs:[xx], al     ; byte store\n"
        ";   2E A3 xx xx CB  mov cs:[xx], ax     ; word store\n"
        ";   2E 88/89 xx CB  reg <-/-> cs:[base+disp]\n"
        "; Evidence: findings 14.  NOT C-portable as written (port as ASM).\n"
    ),
    "LCALL_DISPATCH": (
        "INDIRECT FAR-DISPATCH STUBS (classification: 'lcall cs:[table]; retf')\n"
        ";-----------------------------------------------------------------------\n"
        "; 2E FF 1E xx xx  lcall cs:[xx]   ; call through a CS function-pointer table\n"
        "; CB             retf             ; far-return to original caller\n"
        "; Some members return near (C3) instead - those dispatch into a context\n"
        "; that returns via RET; a few also store a state word (cs:[7DB4h]) after\n"
        "; the call before returning.\n"
        "; Evidence: findings 14.  Table contents live elsewhere in the segment.\n"
    ),
}


def main():
    cls = json.load(open(CLS))
    fb = json.load(open(FB))
    md = Cs(CS_ARCH_X86, CS_MODE_16)

    fam = {}
    for name, info in cls.items():
        r = info["reason"]
        if r.startswith("far stub"):
            fam.setdefault("FAR_THUNK", []).append(name)
        elif r.startswith("CS-relative"):
            fam.setdefault("CS_GETTER", []).append(name)
        elif r.startswith("lcall"):
            fam.setdefault("LCALL_DISPATCH", []).append(name)

    out = [
        "; Falcon 3.0 - annotated hand-ASM family notes (frameless routines)",
        "; GENERATED by tools/gen_asm_families.py - header comments are canonical;",
        "; regenerating updates member lists/disasm only.",
        "; Related evidence: docs/findings_log.md findings 09, 13, 14.",
        "; Byte source of truth: analysis/ida_falconcd/function_bytes.json",
        "",
    ]
    for key in ("FAR_THUNK", "CS_GETTER", "LCALL_DISPATCH"):
        out.append("")
        out.append(FAMILY_HEADERS[key])
        out.append("")
        for name in sorted(fam.get(key, [])):
            info = fb[name]
            b = bytes.fromhex(info["bytes"])
            out.append("; %s  ea=%06X  size=%d" % (name, info["ea"], info["size"]))
            for ins in md.disasm(b, info["ea"]):
                out.append("    %06X  %-14s %-8s %s" % (
                    ins.address, ins.bytes.hex(), ins.mnemonic, ins.op_str))
            # undecoded tail (e.g. bytes after unconditional flow)
            covered = sum(ins.size for ins in md.disasm(b, info["ea"]))
            if covered < len(b):
                out.append("    %06X  %-14s ; undecoded tail" % (
                    info["ea"] + covered, b[covered:].hex()))
            out.append("")

    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(out))
    total = sum(len(v) for v in fam.values())
    print("wrote %s (%d routines annotated)" % (OUT, total))


if __name__ == "__main__":
    main()
