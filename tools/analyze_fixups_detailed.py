from pathlib import Path
import struct

d = Path('game/FALCONCD.EXE').read_bytes()
tail = 0x1fb51
t = d[tail:]

base = 0x2c00 + 0x1AA3 * 16 + 0x0C1F
recs = []
for i in range(100):
    o = base + i * 18
    if o + 18 > len(d):
        break
    w = struct.unpack_from('<9H', d, o)
    if not (0x100 <= w[0] <= 0x9000):
        break
    recs.append(dict(id=w[7], seg=w[0], off=w[2], A=w[4], B=w[5], C=w[6]))

# Disassemble the gap fixup code for key records
try:
    import capstone
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_16)
except:
    md = None

def disasm_gap(gap_bytes, label):
    print(f"\n=== {label} ===")
    if not md:
        print("  (capstone not available)")
        return
    try:
        for insn in md.disasm(bytes(gap_bytes), 0):
            print(f"  {insn.address:04x}: {insn.mnemonic} {insn.op_str}")
    except Exception as e:
        print(f"  Disasm error: {e}")
        print(f"  Raw: {bytes(gap_bytes).hex()}")

