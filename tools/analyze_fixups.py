# Detailed gap analysis for specific segments
def analyze_gap(name, gap_bytes):
    print(f"\n=== {name} ({len(gap_bytes)} bytes) ===")
    print(f"  Hex: {gap_bytes.hex()}")
    print(f"  Bytes: {' '.join(f'{b:02x}' for b in gap_bytes)}")
    # Try to parse as word pairs
    if len(gap_bytes) % 2 == 0:
        words = struct.unpack_from(f'<{len(gap_bytes)//2}H', gap_bytes)
        print(f"  Words: {[f'{w:04x}' for w in words]}")
    # Try to parse as dwords
    if len(gap_bytes) % 4 == 0:
        dwords = struct.unpack_from(f'<{len(gap_bytes)//4}I', gap_bytes)
        print(f"  Dwords: {[f'{dw:08x}' for dw in dwords]}")
    # Check for strings
    try:
        s = gap_bytes.decode('ascii')
        if all(32 <= ord(c) <= 126 or c in '\r\n\t\0' for c in s):
            print(f"  ASCII: {repr(s)}")
    except:
        pass

