# validate: all 30 present, names unique and C-identifier
import re as _re
names = [v[0] for v in analysis.values()]
assert len(analysis) == 30, len(analysis)
assert len(set(names)) == 30, "dup names: %s" % [n for n in names if names.count(n)>1]
bad = [n for n in names if not _re.match(r'^[a-z_][a-z0-9_]*$', n)]
assert not bad, bad
# collision with existing ledger names
txt = io.open('registry/naming.yaml', encoding='utf-8').read()
existing = set(_re.findall(r'name:\s*([a-z_][a-z0-9_]*)', txt))
coll = [n for n in names if n in existing]
print("collisions with existing ledger names:", coll)
print("total new names:", len(names))
