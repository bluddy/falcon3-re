import idc, idaapi, ida_funcs, ida_bytes, idautils, ida_xref, ida_name
out = open(r"C:\Users\ybarnoy\projects\falcon3\analysis\s1\fix_probe.txt", "w")
def P(*a): out.write(" ".join(str(x) for x in a) + "\n")
def xin(lo, hi):
    return sorted((hex(r.frm), hex(x), r.type) for x in range(lo, hi) for r in idautils.XrefsTo(x, 0) if not (lo <= r.frm < hi))
P("before:", xin(0x105D90, 0x105EB5))
ida_bytes.del_items(0x1069BE, ida_bytes.DELIT_SIMPLE, 10)
for a in range(0x1069BE, 0x1069C8, 2): ida_bytes.create_word(a, 2)
P("after word fix:", xin(0x105D90, 0x105EB5))
P("1069B4 item:", idc.generate_disasm_line(0x1069B4, 0), "| 1069BE:", idc.generate_disasm_line(0x1069BE, 0))
for ea in (0x105DA7, 0x105D9D): ida_funcs.del_func(ea); ida_name.set_name(ea, "", ida_name.SN_NOWARN)
P("after del_func:", xin(0x105D90, 0x105EB5))
ida_bytes.del_items(0x105D90, ida_bytes.DELIT_SIMPLE, 0x105EB5 - 0x105D90)
P("after del_items:", xin(0x105D90, 0x105EB5))
for a in range(0x105D90, 0x105DE6, 2): ida_bytes.create_word(a, 2)
P("heads:", [(hex(a), idc.generate_disasm_line(a, 0)[:20]) for a in (0x105D90, 0x105D9D, 0x105DA7, 0x105DE4, 0x105DE6)])
P("code heads left in 105D90..105EB5:", sum(1 for x in range(0x105D90, 0x105EB5) if ida_bytes.is_code(ida_bytes.get_flags(x))))
P("flags 105DE6:", hex(ida_bytes.get_flags(0x105DE6)))
out.close(); idc.qexit(0)
