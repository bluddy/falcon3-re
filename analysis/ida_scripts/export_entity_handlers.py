import idc
import idaapi
import idautils
import json
from pathlib import Path

def export_function_disasm(func_addr, name, max_lines=150):
    """Export function disassembly."""
    func = idaapi.get_func(func_addr)
    if not func:
        return None
    
    fname = idc.get_func_name(func.start_ea)
    size = func.end_ea - func.start_ea
    
    # Get disassembly
    disasm_lines = []
    ea = func.start_ea
    offset = 0
    line_count = 0
    
    while ea < func.end_ea and line_count < max_lines:
        disasm = idc.generate_disasm_line(ea, 0)
        comment = idc.get_cmt(ea, 0) or idc.get_cmt(ea, 1)
        
        line_info = {
            "offset": offset,
            "address": hex(ea),
            "disasm": disasm
        }
        if comment:
            line_info["comment"] = comment
        
        disasm_lines.append(line_info)
        
        next_ea = idc.next_head(ea, func.end_ea)
        offset += next_ea - ea
        ea = next_ea
        line_count += 1
    
    # Find calls
    calls_from = []
    ea = func.start_ea
    while ea < func.end_ea:
        mnem = idc.print_insn_mnem(ea)
        if mnem in ["call", "callf"]:
            target = idc.get_operand_value(ea, 0)
            if target != idc.BADADDR:
                target_name = idc.get_func_name(target)
                if target_name:
                    calls_from.append({
                        "at": hex(ea),
                        "to": hex(target),
                        "name": target_name
                    })
        ea = idc.next_head(ea, func.end_ea)
    
    return {
        "name": fname,
        "address": hex(func.start_ea),
        "size": size,
        "calls_from": calls_from,
        "disasm": disasm_lines,
        "truncated": line_count >= max_lines
    }

