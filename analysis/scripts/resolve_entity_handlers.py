"""
Resolve all entity handler addresses from the dispatch table.
Calculate linear addresses using seg020 base and export handlers.
"""

import json
import sys
from pathlib import Path

def main():
    print("=" * 80)
    print("Entity Handler Address Resolution")
    print("=" * 80)
    print()
    
    # seg020 base address (from segment_map.json)
    seg020_base = 0x1F6C0
    
    # Dispatch table entries (from extract_farobj_dispatch_table.py output)
    # Even indices only (odd indices are all 0x1F6C - default handler)
    handlers = {
        0: 0x900E,
        2: 0x90B4,
        4: 0x8A87,
        6: 0x7AC0,
        8: 0x7A7D,
        10: 0x7618,
        12: 0x758A,
        14: 0x746E,
        16: 0x7389,
        18: 0x721D,
        20: 0x70AD,
        22: 0x6E05,
        24: 0x8360,
        26: 0x8357,
    }
    
    # Default handler (odd indices)
    default_handler = 0x1F6C
    
    print("Dispatch Table Handler Resolution")
    print("-" * 80)
    print(f"seg020 base: 0x{seg020_base:X}")
    print(f"Default handler (odd indices): 0x{default_handler:04X}")
    print()
    
    # Calculate linear addresses
    resolved_handlers = []
    
    for idx, offset in sorted(handlers.items()):
        linear = seg020_base + offset
        
        handler_info = {
            'index': idx,
            'offset': offset,
            'linear': linear,
            'segoff': f'seg020:{offset:04X}'
        }
        
        resolved_handlers.append(handler_info)
        
        print(f"Handler[{idx:2}]: offset=0x{offset:04X} -> linear=0x{linear:05X} (seg020:{offset:04X})")
    
    print()
    print(f"Total handlers: {len(resolved_handlers)}")
    print()
    
    # Use address translator to find function names
    print("=" * 80)
    print("Looking up function names...")
    print("=" * 80)
    print()
    
    # Generate address translator commands
    translator_path = Path(__file__).parent.parent / "s4" / "address_translator.py"
    segment_map = Path(__file__).parent.parent / "s4" / "segment_map.json"
    
    if not translator_path.exists() or not segment_map.exists():
        print(f"WARNING: Address translator not found")
        print(f"  Expected: {translator_path}")
        return 1
    
    import subprocess
    
    for handler in resolved_handlers:
        linear = handler['linear']
        
        # Run address translator
        result = subprocess.run(
            ['python', str(translator_path), str(segment_map), 'find', f"0x{linear:X}"],
            capture_output=True,
            text=True,
            cwd=str(translator_path.parent)
        )
        
        if result.returncode == 0:
            output = result.stdout.strip()
            
            # Parse output to extract function name
            for line in output.split('\n'):
                if 'function:' in line.lower():
                    func_name = line.split(':')[-1].strip()
                    handler['function_name'] = func_name
                    print(f"Handler[{handler['index']:2}]: {func_name}")
                    break
        else:
            handler['function_name'] = '???'
            print(f"Handler[{handler['index']:2}]: ??? (not found)")
    
    print()
    
    # Save results
    output = {
        'seg020_base': hex(seg020_base),
        'default_handler': {
            'offset': hex(default_handler),
            'linear': hex(seg020_base + default_handler),
            'note': 'Used for all odd indices (1, 3, 5, ...)'
        },
        'handlers': resolved_handlers
    }
    
    output_json = Path(__file__).parent.parent / "ida_scripts" / "entity_handlers_resolved.json"
    with open(output_json, 'w') as f:
        json.dump(output, f, indent=2)
    
    print(f"OK Saved to: {output_json}")
    print()
    
    # Generate IDA export script for these handlers
    print("=" * 80)
    print("Generating IDA export script...")
    print("=" * 80)
    print()
    
    script_lines = [
        '"""',
        'Export entity type handler functions.',
        'Generated by resolve_entity_handlers.py',
        '"""',
        '',
        'import idc',
        'import idaapi',
        'import idautils',
        'import json',
        'from pathlib import Path',
        '',
        'def export_function_disasm(func_addr, name, max_lines=150):',
        '    """Export function disassembly."""',
        '    func = idaapi.get_func(func_addr)',
        '    if not func:',
        '        return None',
        '    ',
        '    fname = idc.get_func_name(func.start_ea)',
        '    size = func.end_ea - func.start_ea',
        '    ',
        '    # Get disassembly',
        '    disasm_lines = []',
        '    ea = func.start_ea',
        '    offset = 0',
        '    line_count = 0',
        '    ',
        '    while ea < func.end_ea and line_count < max_lines:',
        '        disasm = idc.generate_disasm_line(ea, 0)',
        '        comment = idc.get_cmt(ea, 0) or idc.get_cmt(ea, 1)',
        '        ',
        '        line_info = {',
        '            "offset": offset,',
        '            "address": hex(ea),',
        '            "disasm": disasm',
        '        }',
        '        if comment:',
        '            line_info["comment"] = comment',
        '        ',
        '        disasm_lines.append(line_info)',
        '        ',
        '        next_ea = idc.next_head(ea, func.end_ea)',
        '        offset += next_ea - ea',
        '        ea = next_ea',
        '        line_count += 1',
        '    ',
        '    # Find calls',
        '    calls_from = []',
        '    ea = func.start_ea',
        '    while ea < func.end_ea:',
        '        mnem = idc.print_insn_mnem(ea)',
        '        if mnem in ["call", "callf"]:',
        '            target = idc.get_operand_value(ea, 0)',
        '            if target != idc.BADADDR:',
        '                target_name = idc.get_func_name(target)',
        '                if target_name:',
        '                    calls_from.append({',
        '                        "at": hex(ea),',
        '                        "to": hex(target),',
        '                        "name": target_name',
        '                    })',
        '        ea = idc.next_head(ea, func.end_ea)',
        '    ',
        '    return {',
        '        "name": fname,',
        '        "address": hex(func.start_ea),',
        '        "size": size,',
        '        "calls_from": calls_from,',
        '        "disasm": disasm_lines,',
        '        "truncated": line_count >= max_lines',
        '    }',
        '',
        'def main():',
        '    print("Exporting entity type handlers...")',
        '    print()',
        '    ',
        '    idaapi.auto_wait()',
        '    ',
        '    handlers = [',
    ]
    
    # Add handler addresses
    for handler in resolved_handlers:
        linear = handler['linear']
        idx = handler['index']
        func_name = handler.get('function_name', 'unknown')
        script_lines.append(f'        (0x{linear:X}, {idx}, "{func_name}"),')
    
    script_lines.extend([
        '    ]',
        '    ',
        '    results = {}',
        '    ',
        '    for addr, idx, name in handlers:',
        '        print(f"Exporting handler[{idx}]: {name} at 0x{addr:X}...")',
        '        result = export_function_disasm(addr, name)',
        '        ',
        '        if result:',
        '            result["handler_index"] = idx',
        '            results[f"handler_{idx:02d}_{result[\\"name\\"]}"] = result',
        '            print(f"  Size: {result[\\"size\\"]} bytes")',
        '            print(f"  Calls: {len(result[\\"calls_from\\"])}")',
        '        else:',
        '            print(f"  ERROR: No function at address")',
        '        print()',
        '    ',
        '    # Save JSON',
        '    output_json = Path(__file__).parent / "entity_handlers_disasm.json"',
        '    with open(output_json, "w") as f:',
        '        json.dump(results, f, indent=2)',
        '    ',
        '    print(f"✓ Saved {len(results)} handlers to: {output_json}")',
        '    ',
        '    # Save text files',
        '    for key, data in results.items():',
        '        output_txt = Path(__file__).parent.parent / "disassembly" / f"{key}_disasm.txt"',
        '        ',
        '        with open(output_txt, "w") as f:',
        '            f.write("=" * 80 + "\\n")',
        '            f.write(f"{data[\\"name\\"]} - Handler[{data[\\"handler_index\\"]}]\\n")',
        '            f.write("=" * 80 + "\\n")',
        '            f.write(f"Address: {data[\\"address\\"]}\\n")',
        '            f.write(f"Size: {data[\\"size\\"]} bytes\\n")',
        '            f.write(f"Entity Type Index: {data[\\"handler_index\\"]}\\n")',
        '            if data.get("truncated"):',
        '                f.write("NOTE: Disassembly truncated to 150 lines\\n")',
        '            f.write("=" * 80 + "\\n\\n")',
        '            ',
        '            if data["calls_from"]:',
        '                f.write(f"Calls {len(data[\\"calls_from\\"])} functions:\\n")',
        '                for call in data["calls_from"]:',
        '                    f.write(f"  {call[\\"at\\"]} -> {call[\\"name\\"]}\\n")',
        '                f.write("\\n")',
        '            ',
        '            f.write("=" * 80 + "\\n")',
        '            f.write("Disassembly:\\n")',
        '            f.write("=" * 80 + "\\n\\n")',
        '            ',
        '            for i, line in enumerate(data["disasm"]):',
        '                f.write(f"{i:4} | +0x{line[\\"offset\\"]:04X} | {line[\\"address\\"]} | {line[\\"disasm\\"]}")',
        '                if "comment" in line:',
        '                    f.write(f"  ; {line[\\"comment\\"]}")',
        '                f.write("\\n")',
        '    ',
        '    print(f"✓ Saved {len(results)} text files")',
        '    idc.qexit(0)',
        '',
        'if __name__ == "__main__":',
        '    main()',
    ])
    
    script_path = Path(__file__).parent.parent / "ida_scripts" / "export_entity_handlers.py"
    with open(script_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(script_lines))
    
    print(f"OK IDA script: {script_path}")
    print()
    
    print("=" * 80)
    print("Next Steps")
    print("=" * 80)
    print()
    print("1. Run the IDA export script:")
    print('   & "C:\\Program Files\\IDA Professional 9.1\\idat.exe" -A \\')
    print('     -S"analysis\\ida_scripts\\export_entity_handlers.py" \\')
    print('     "analysis\\ida_falconcd\\FALCONCD.EXE.i64"')
    print()
    print("2. Analyze the exported handlers to determine entity types")
    print()
    
    return 0

if __name__ == "__main__":
    sys.exit(main())
